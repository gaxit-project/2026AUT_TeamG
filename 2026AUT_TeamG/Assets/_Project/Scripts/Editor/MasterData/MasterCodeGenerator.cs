using System.IO;
using System.Linq;
using System.Text;

namespace TeamG.EditorTools
{
    /// <summary>MasterSheet の定義から Record クラスと Master（ScriptableObject）クラスを生成する。</summary>
    internal static class MasterCodeGenerator
    {
        /// <summary>生成コードを書き出す。中身が変わったときだけ書き込み、true を返す（不要な再コンパイルを避けるため）。</summary>
        public static bool Write(MasterSheet sheet, string outputDirectory)
        {
            var path = Path.Combine(outputDirectory, sheet.TableClassName + ".cs");
            var code = Build(sheet);
            if (File.Exists(path) && File.ReadAllText(path) == code)
            {
                return false;
            }

            Directory.CreateDirectory(outputDirectory);
            File.WriteAllText(path, code, new UTF8Encoding(false));
            return true;
        }

        public static string Build(MasterSheet sheet)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append($"// MasterData/{sheet.FileName} から自動生成しています。手で編集しないでください。\n");
            sb.Append("// 変更するときは CSV を直して、Unity のメニュー「TeamG > マスターデータ > 変換」を実行します。\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("#pragma warning disable 0649 // SerializeField は変換ツールが値を入れる\n");
            sb.Append("using System;\n");
            sb.Append("using UnityEngine;\n");
            sb.Append("\n");
            sb.Append("namespace TeamG.Data\n");
            sb.Append("{\n");
            sb.Append("    [Serializable]\n");
            sb.Append($"    public sealed class {sheet.RecordClassName} : IMasterRecord\n");
            sb.Append("    {\n");

            foreach (var column in sheet.Columns)
            {
                sb.Append($"        [SerializeField] {column.CSharpType} {column.FieldIdentifier};\n");
            }

            foreach (var column in sheet.Columns)
            {
                sb.Append("\n");
                if (column.Description.Length > 0)
                {
                    sb.Append($"        /// <summary>{Escape(column.Description)}</summary>\n");
                }
                sb.Append($"        public {column.CSharpType} {column.Name} => {column.FieldIdentifier};\n");
            }

            sb.Append("    }\n");
            sb.Append("\n");
            sb.Append($"    public sealed class {sheet.TableClassName} : MasterTable<{sheet.RecordClassName}>\n");
            sb.Append("    {\n");
            sb.Append("    }\n");
            sb.Append("}\n");
            return sb.ToString();
        }

        static string Escape(string text)
        {
            var oneLine = string.Join(" ", text.Split('\n').Select(l => l.Trim()));
            return oneLine.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }
    }
}
